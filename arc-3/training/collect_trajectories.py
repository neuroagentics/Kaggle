"""Trajectory collector — R10 data generation from MIT-licensed environments.

Runs the ARC Prize Foundation environment files (MIT-licensed, in
environment_files/) locally through arcengine to produce
observation → action → outcome trajectories for training the simulator.

This is legitimate, cleared training data:
  - The environments are MIT-licensed (ARC Prize Foundation) — sharing/derived
    use is explicitly permitted.
  - Trajectories are generated by our own play, authored by us.
  - No hidden engine internals are read: only the public FrameData that a real
    agent would observe (settled grid, state, level, available actions).

Output: JSONL, one trajectory per line, each a dict:
    {
      "game_id": str,
      "env_dir": str,            # provenance: which environment file
      "seed": int,
      "policy": str,             # how actions were chosen
      "steps": [                 # ordered transitions
        {"grid": [[...]], "action_id": int, "action_x": int|None,
         "action_y": int|None, "level": int, "state": str,
         "available_actions": [int, ...]},
        ...
      ]
    }

The first step's grid is the post-RESET observation. Each subsequent step records
the action taken FROM the previous grid and the resulting settled grid/level/state.

No PyTorch needed here — pure environment play. Training consumes the JSONL.
"""
from __future__ import annotations

import argparse
import importlib.util
import inspect
import json
import random
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Iterator

# Ensure arcengine (and the vendored framework, if present) are importable.
_ROOT = Path(__file__).resolve().parents[1]
for _p in (_ROOT, _ROOT / "vendor" / "ARC-AGI-3-Agents"):
    sp = str(_p)
    if sp not in sys.path:
        sys.path.insert(0, sp)

from arcengine import ARCBaseGame, ActionInput, GameAction, GameState  # noqa: E402

ENV_ROOT = _ROOT / "environment_files"


# ---------------------------------------------------------------------------
# Environment discovery / loading
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class EnvSpec:
    game_key: str      # top-level dir name, e.g. 'cd82'
    env_dir: Path      # the leaf dir containing the .py + metadata.json
    module_path: Path  # the .py file


def discover_environments(env_root: Path = ENV_ROOT) -> list[EnvSpec]:
    """Find every environment file: environment_files/<game>/<hash>/<game>.py."""
    specs: list[EnvSpec] = []
    if not env_root.is_dir():
        return specs
    for game_dir in sorted(env_root.iterdir()):
        if not game_dir.is_dir():
            continue
        for leaf in sorted(game_dir.iterdir()):
            if not leaf.is_dir():
                continue
            py = leaf / f"{game_dir.name}.py"
            if py.is_file():
                specs.append(EnvSpec(game_dir.name, leaf, py))
    return specs


def load_game_class(spec: EnvSpec):
    """Import the env module and return its ARCBaseGame subclass (no-arg ctor)."""
    mod_name = f"arc3_env_{spec.game_key}"
    module_spec = importlib.util.spec_from_file_location(mod_name, spec.module_path)
    if module_spec is None or module_spec.loader is None:
        raise ImportError(f"Cannot load env module: {spec.module_path}")
    module = importlib.util.module_from_spec(module_spec)
    module_spec.loader.exec_module(module)
    candidates = [
        obj for _, obj in inspect.getmembers(module, inspect.isclass)
        if issubclass(obj, ARCBaseGame) and obj is not ARCBaseGame
        and obj.__module__ == mod_name
    ]
    if not candidates:
        raise ImportError(f"No ARCBaseGame subclass in {spec.module_path}")
    # If several, pick the one whose name matches the game key most closely.
    candidates.sort(key=lambda c: (c.__name__.lower() != spec.game_key.lower(), c.__name__))
    return candidates[0]


# ---------------------------------------------------------------------------
# Playing policy
# ---------------------------------------------------------------------------

def _settled_grid(frame) -> list[list[int]]:
    """Last frame in the animation stack is the settled board."""
    if not frame.frame:
        return []
    return [[int(v) for v in row] for row in frame.frame[-1]]


def _changed_cells(a: list[list[int]], b: list[list[int]]) -> int:
    if not a or not b or len(a) != len(b) or len(a[0]) != len(b[0]):
        return -1
    return sum(x != y for ra, rb in zip(a, b) for x, y in zip(ra, rb))


def _grid_hash(grid: list[list[int]]) -> int:
    """Cheap stable hash of a settled grid for novelty counting."""
    return hash(tuple(tuple(row) for row in grid))


class ExplorerPolicy:
    """Count-based novelty + progress-seeking exploration.

    The old weighted-random policy almost never made level progress (diagnosis:
    42537/42893 observations stuck at level 0). This policy reaches deeper,
    goal-relevant states by:
      - Counting visited state hashes and preferring actions that reach LESS-seen
        states (count-based novelty, the classic tabular exploration bonus).
      - Rewarding any action that increased levels_completed (progress) so the
        collector lingers where mechanics actually fire.
      - Down-weighting actions that recently no-oped (no state change).
      - Occasionally probing ACTION6 on content coordinates.
    It carries per-trajectory state; construct one per trajectory.

    This is a DATA-GENERATION policy, not the agent's reasoning policy.
    """

    def __init__(self, rng: random.Random, mode: str = "novelty"):
        self.rng = rng
        self._mode = mode                                    # 'random'|'streak'|'novelty'
        self._state_counts: dict[int, int] = {}
        self._edge_noops: dict[tuple[int, int], int] = {}   # (state_hash, action) -> noop count
        self._action_progress: dict[int, float] = {}         # action -> progress credit
        self._last_hash: int | None = None
        self._streak_action: int = -1
        self._streak_left: int = 0

    def observe(self, grid: list[list[int]]) -> int:
        h = _grid_hash(grid)
        self._state_counts[h] = self._state_counts.get(h, 0) + 1
        self._last_hash = h
        return h

    def record_outcome(self, state_hash: int, action_id: int,
                       changed: int, level_delta: int) -> None:
        if changed == 0:
            self._edge_noops[(state_hash, action_id)] = \
                self._edge_noops.get((state_hash, action_id), 0) + 1
        if level_delta > 0:
            # Strong, lasting credit for actions that made real progress.
            self._action_progress[action_id] = \
                self._action_progress.get(action_id, 0.0) + 5.0 * level_delta

    def choose(self, available: list[int], grid: list[list[int]]
               ) -> tuple[int, int | None, int | None]:
        state_hash = self._last_hash if self._last_hash is not None else _grid_hash(grid)
        simple = [a for a in available
                  if a not in (GameAction.ACTION6.value, GameAction.RESET.value)]
        has_click = GameAction.ACTION6.value in available

        # Occasional content-click probe.
        if has_click and (not simple or self.rng.random() < 0.15):
            pt = _sample_content_coord(self.rng, grid)
            return GameAction.ACTION6.value, pt[0], pt[1]
        if not simple:
            if has_click:
                pt = _sample_content_coord(self.rng, grid)
                return GameAction.ACTION6.value, pt[0], pt[1]
            return GameAction.RESET.value, None, None

        # 'random' mode: pure random over simple actions. Diagnosis showed
        # progress in these games needs specific action SEQUENCES that random
        # play occasionally hits by chance; novelty-seeking actively avoids the
        # repeated setup states those sequences need. So we keep BOTH.
        if self._mode == "random":
            return self.rng.choice(simple), None, None

        # 'streak' mode: commit to a run of the same action to explore sequences
        # (many mechanics need the avatar to travel/repeat before something fires).
        if self._mode == "streak":
            if self._streak_action in simple and self._streak_left > 0:
                self._streak_left -= 1
                return self._streak_action, None, None
            self._streak_action = self.rng.choice(simple)
            self._streak_left = self.rng.randint(2, 6)
            return self._streak_action, None, None

        # 'novelty' (default): progress credit + novelty, epsilon-greedy.
        scored = []
        for a in simple:
            noop = self._edge_noops.get((state_hash, a), 0)
            progress = self._action_progress.get(a, 0.0)
            novelty = 1.0 / (1.0 + noop)
            score = progress + novelty + self.rng.random() * 0.3
            scored.append((score, a))
        scored.sort(reverse=True)
        if self.rng.random() < 0.2:
            return self.rng.choice(simple), None, None
        return scored[0][1], None, None


def _sample_content_coord(rng: random.Random, grid: list[list[int]]) -> tuple[int, int]:
    if not grid or not grid[0]:
        return 32, 32
    h, w = len(grid), len(grid[0])
    # background = most common edge color
    from collections import Counter
    edge = grid[0] + grid[-1] + [grid[y][0] for y in range(h)] + [grid[y][w - 1] for y in range(h)]
    bg = Counter(edge).most_common(1)[0][0]
    content = [(x, y) for y in range(h) for x in range(w) if grid[y][x] != bg]
    if content:
        return content[rng.randrange(len(content))]
    return rng.randrange(w), rng.randrange(h)


# ---------------------------------------------------------------------------
# Trajectory generation
# ---------------------------------------------------------------------------

def play_trajectory(
    game_cls,
    *,
    seed: int,
    max_steps: int,
    rng: random.Random,
    mode: str = "novelty",
) -> dict:
    """Play one trajectory and return its record."""
    try:
        game = game_cls()
    except Exception as exc:
        raise RuntimeError(f"Could not construct {game_cls.__name__}: {exc}") from exc

    steps: list[dict] = []
    frame = game.perform_action(ActionInput(id=GameAction.RESET))
    grid = _settled_grid(frame)
    policy = ExplorerPolicy(rng, mode=mode)

    for _ in range(max_steps):
        available = [int(a) for a in frame.available_actions] or [1, 2, 3, 4, 5, 6]
        state_hash = policy.observe(grid)
        prev_level = int(frame.levels_completed)
        aid, ax, ay = policy.choose(available, grid)

        # Record the observation BEFORE the action (the state the action is taken from).
        step_record = {
            "grid": grid,
            "action_id": aid,
            "action_x": ax,
            "action_y": ay,
            "level": prev_level,
            "state": frame.state.value if hasattr(frame.state, "value") else str(frame.state),
            "available_actions": available,
        }
        steps.append(step_record)

        # Apply the action.
        action = GameAction.from_id(aid)
        data = {"x": ax, "y": ay} if aid == GameAction.ACTION6.value else {}
        try:
            frame = game.perform_action(ActionInput(id=action, data=data))
        except Exception:
            break

        new_grid = _settled_grid(frame)
        changed = _changed_cells(grid, new_grid)
        level_delta = max(0, int(frame.levels_completed) - prev_level)
        policy.record_outcome(state_hash, aid, changed, level_delta)
        grid = new_grid

        if frame.state in (GameState.WIN, GameState.GAME_OVER):
            # Record the terminal observation as a final step (no action from it).
            steps.append({
                "grid": grid,
                "action_id": None,
                "action_x": None,
                "action_y": None,
                "level": int(frame.levels_completed),
                "state": frame.state.value if hasattr(frame.state, "value") else str(frame.state),
                "available_actions": [int(a) for a in frame.available_actions],
            })
            break

    return {"steps": steps}


def collect(
    specs: list[EnvSpec],
    *,
    out_path: Path,
    trajectories_per_game: int,
    max_steps: int,
    base_seed: int,
) -> dict:
    """Collect trajectories for all specs, writing JSONL. Returns a summary."""
    out_path.parent.mkdir(parents=True, exist_ok=True)
    summary = {
        "games": [],
        "total_trajectories": 0,
        "total_transitions": 0,
        "failures": [],
    }
    with out_path.open("w", encoding="utf-8") as f:
        for spec in specs:
            try:
                game_cls = load_game_class(spec)
            except Exception as exc:
                summary["failures"].append({"game": spec.game_key, "error": str(exc)})
                continue
            game_traj = 0
            game_trans = 0
            # Rotate exploration modes so we keep random's chance discoveries,
            # streak's sequence exploration, and novelty's coverage.
            modes = ("random", "streak", "novelty")
            for t in range(trajectories_per_game):
                seed = base_seed + hash((spec.game_key, t)) % 100000
                rng = random.Random(seed)
                mode = modes[t % len(modes)]
                try:
                    record = play_trajectory(
                        game_cls, seed=seed, max_steps=max_steps, rng=rng, mode=mode
                    )
                except Exception as exc:
                    summary["failures"].append(
                        {"game": spec.game_key, "traj": t, "error": str(exc)}
                    )
                    continue
                record.update({
                    "game_id": spec.game_key,
                    "env_dir": str(spec.env_dir.relative_to(_ROOT)),
                    "seed": seed,
                    "policy": f"mixed-explore-v3:{mode}",
                })
                f.write(json.dumps(record) + "\n")
                game_traj += 1
                game_trans += max(0, len(record["steps"]) - 1)
            summary["games"].append({
                "game": spec.game_key,
                "trajectories": game_traj,
                "transitions": game_trans,
            })
            summary["total_trajectories"] += game_traj
            summary["total_transitions"] += game_trans
            print(
                f"[collect] {spec.game_key}: {game_traj} trajectories, "
                f"{game_trans} transitions", flush=True,
            )
    return summary


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Collect ARC-3 training trajectories")
    parser.add_argument("--out", type=Path, default=_ROOT / "training" / "data" / "trajectories.jsonl")
    parser.add_argument("--games", type=str, default="", help="Comma-separated game keys; default all")
    parser.add_argument("--per-game", type=int, default=20)
    parser.add_argument("--max-steps", type=int, default=60)
    parser.add_argument("--seed", type=int, default=1234)
    parser.add_argument("--summary", type=Path, default=None)
    args = parser.parse_args(argv)

    specs = discover_environments()
    if args.games:
        wanted = {g.strip() for g in args.games.split(",") if g.strip()}
        specs = [s for s in specs if s.game_key in wanted]
    if not specs:
        print("No environments found.", file=sys.stderr)
        return 1

    print(f"[collect] {len(specs)} environment(s): {[s.game_key for s in specs]}", flush=True)
    summary = collect(
        specs,
        out_path=args.out,
        trajectories_per_game=args.per_game,
        max_steps=args.max_steps,
        base_seed=args.seed,
    )
    summary_path = args.summary or args.out.with_suffix(".summary.json")
    summary_path.write_text(json.dumps(summary, indent=2), encoding="utf-8")
    print(
        f"[collect] DONE: {summary['total_trajectories']} trajectories, "
        f"{summary['total_transitions']} transitions, "
        f"{len(summary['failures'])} failures -> {args.out}", flush=True,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
